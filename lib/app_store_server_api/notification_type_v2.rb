# frozen_string_literal: true

module AppStoreServerApi
  # The `notificationType` values Apple sends in App Store Server Notifications
  # V2. Mirrors Apple's official `NotificationTypeV2` enum (ported from the
  # MIT-licensed apple/app-store-server-library-python) so consumers can branch
  # on named constants instead of string literals.
  #
  # https://developer.apple.com/documentation/appstoreservernotifications/notificationtype
  module NotificationTypeV2
    SUBSCRIBED = "SUBSCRIBED"
    DID_CHANGE_RENEWAL_PREF = "DID_CHANGE_RENEWAL_PREF"
    DID_CHANGE_RENEWAL_STATUS = "DID_CHANGE_RENEWAL_STATUS"
    OFFER_REDEEMED = "OFFER_REDEEMED"
    DID_RENEW = "DID_RENEW"
    EXPIRED = "EXPIRED"
    DID_FAIL_TO_RENEW = "DID_FAIL_TO_RENEW"
    GRACE_PERIOD_EXPIRED = "GRACE_PERIOD_EXPIRED"
    PRICE_INCREASE = "PRICE_INCREASE"
    REFUND = "REFUND"
    REFUND_DECLINED = "REFUND_DECLINED"
    CONSUMPTION_REQUEST = "CONSUMPTION_REQUEST"
    RENEWAL_EXTENDED = "RENEWAL_EXTENDED"
    REVOKE = "REVOKE"
    TEST = "TEST"
    RENEWAL_EXTENSION = "RENEWAL_EXTENSION"
    REFUND_REVERSED = "REFUND_REVERSED"
    EXTERNAL_PURCHASE_TOKEN = "EXTERNAL_PURCHASE_TOKEN"
    ONE_TIME_CHARGE = "ONE_TIME_CHARGE"
    RESCIND_CONSENT = "RESCIND_CONSENT"
    METADATA_UPDATE = "METADATA_UPDATE"
    MIGRATION = "MIGRATION"
    PRICE_CHANGE = "PRICE_CHANGE"

    # Every known notification type, for validation/enumeration.
    ALL = [
      SUBSCRIBED, DID_CHANGE_RENEWAL_PREF, DID_CHANGE_RENEWAL_STATUS,
      OFFER_REDEEMED, DID_RENEW, EXPIRED, DID_FAIL_TO_RENEW,
      GRACE_PERIOD_EXPIRED, PRICE_INCREASE, REFUND, REFUND_DECLINED,
      CONSUMPTION_REQUEST, RENEWAL_EXTENDED, REVOKE, TEST, RENEWAL_EXTENSION,
      REFUND_REVERSED, EXTERNAL_PURCHASE_TOKEN, ONE_TIME_CHARGE,
      RESCIND_CONSENT, METADATA_UPDATE, MIGRATION, PRICE_CHANGE
    ].freeze
  end
end
